# 小句边界豁免在**调用方**（qc_subs.check）里，不在 crossing_word 里——
# 断点落在标点处时本来就不可能劈开词。所以这两条要走端到端，
# 光调 crossing_word 会把「回报会更高 / 一星级…」报成劈开「高一」。
CLAUSE_EXEMPT = [
    ('那这个所谓的A股', '它包含哪些板块呢'),
    ('回报会更高', '一星级的时候就是'),
]


def test_crossing():
    import qc_subs as Q
    for a, b, want in CROSS_CASES:
        got = Q.crossing_word(a, b)
        assert got and (want in got or got == want), \
            '期望报「%s」，实际「%s」：%s | %s' % (want, got, a, b)
    for a, b in CLAUSE_EXEMPT:
        lines = [{'text': a, 'start': 0.0, 'end': 1.0, 'clause_start': True},
                 {'text': b, 'start': 1.0, 'end': 2.0, 'clause_start': True}]
        errs, _ = Q.check(lines)
        hit = [e for e in errs if '断行劈开' in e[1]]
        assert not hit, '小句边界不该报断行：%s | %s -> %s' % (a, b, hit)
    return len(CROSS_CASES) + len(CLAUSE_EXEMPT)


def run():
    bad = []
    import qc_subs as Q
    for line, want, why in LEADSTART_CASES:
        errs, _ = Q.check([line])
        got = sum(1 for e in errs if '虚词' in e[1])
        if got != want:
            bad.append(('lead', line['text'] + (' (小句开头)' if line['clause_start'] else ' (句中)'),
                        '虚词错 %d 处' % want, '虚词错 %d 处' % got, why))
    for pair, want, why in PREFIX_CASES:
        errs, _ = Q.check([{'text': x, 'start': j, 'end': j+2} for j, x in enumerate(pair)])
        got = sum(1 for e in errs if '专名' in e[1])
        if got != want:
            bad.append(('prefix', ' / '.join(pair), '专名错 %d 处' % want, '专名错 %d 处' % got, why))
    for t, want, why in BOOK_CASES:
        errs, _ = Q.check([{'text': t, 'start': 0, 'end': 3}])
        got = sum(1 for e in errs if '书名' in e[1])
        if got != want:
            bad.append(('book', t, '书名错 %d 处' % want, '书名错 %d 处' % got, why))
    for t, want, why in WIDTH_CASES:
        for name, fn in (('make_srt', lambda x: sum(M.char_width(c) for c in x)),
                         ('qc_subs', Q.width)):
            got = fn(t)
            if abs(got - want) > 0.005:
                bad.append(('width', '%s: %s' % (name, t), '%.3f em' % want, '%.3f em' % got, why))
    for parts, max_em, should_block, why in LEADING_CASES:
        ps = [(t, list(range(len(t)))) for t in parts]
        out = M.fix_leading(ps, max_em)
        w = sum(M.char_width(c) for c in out[0][0])
        over = w > max_em
        moved = len(out[0][0]) > len(parts[0])
        if over:
            bad.append(('leading', ' / '.join(parts), '首行不得超 %.1fem' % max_em,
                        '实际 %.1fem' % w, why))
        elif should_block and moved:
            bad.append(('leading', ' / '.join(parts), '不该并回（会超宽）', '并回了', why))
        elif not should_block and not moved:
            bad.append(('leading', ' / '.join(parts), '应该并回', '没并回', why))
    for src, want, why in CLEAN_CASES:
        got = M.clean_script(src)
        if got != want:
            bad.append(('clean', src, want, got, why))
    for prev, nxt, should_penalize, why in BREAK_CASES:
        c = M.break_cost(prev, nxt)
        hit = c >= 60
        if hit != should_penalize:
            bad.append(('break', '%s | %s' % (prev, nxt),
                        '应重罚' if should_penalize else '不该罚', '代价=%d' % c, why))

    extra = 0
    for fn in (test_lexicon, test_crossing):
        try:
            extra += fn()
        except AssertionError as e:
            bad.append((fn.__name__, '-', '通过', str(e), fn.__doc__ or fn.__name__))

    total = (len(CLEAN_CASES) + len(BREAK_CASES) + len(LEADING_CASES)
             + len(WIDTH_CASES)*2 + len(BOOK_CASES) + len(PREFIX_CASES)
             + len(LEADSTART_CASES) + extra)
    print('字幕规则回归测试：%d 条用例' % total)
    if not bad:
        print('✅ 全部通过')
        return 0
    print('❌ %d 条失败\n' % len(bad))
    for kind, src, want, got, why in bad:
        print('  [%s] %s' % (kind, why))
        print('     输入：%s' % src)
        print('     期望：%s' % want)
        print('     实际：%s\n' % got)
    return 1


